#!/usr/bin/env python3
"""docs/refactor/terminal-inventory.md: every method of TerminalTab / TerminalNotebook with its test coverage.

    tools/refactor_terminal_inventory.py COVERAGE.json > docs/refactor/terminal-inventory.md

COVERAGE.json is ``tools/line_coverage.py`` output of a full suite run. Methods of the broadcast area
(§2.4.4: broadcast, the ended-session ``q`` / ``r`` keys and Close, the tile header chips) are marked, so a
method there without a test stands out.
"""

from __future__ import annotations

import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILE = "ophion/gtk_terminal.py"
CLASSES = ("TerminalTab", "TerminalNotebook")
BROADCAST = re.compile(r"broadcast|ended|reconnect|close|chip|include|peer|feed_input|request_close|_on_key",
                       re.IGNORECASE)


def main(argv) -> int:
    coverage = json.loads(Path(argv[0]).read_text(encoding="utf-8"))[FILE]["functions"]
    tree = ast.parse((ROOT / FILE).read_text(encoding="utf-8"))
    out = ["# Terminal inventory (coverage per method)", "",
           "Generated by `tools/refactor_terminal_inventory.py` from `tools/line_coverage.py` output of the full",
           "suite on the private X server. Lines: executed / executable (the `def` line runs at import).",
           "**B** = broadcast area (§2.4.4). A method of it with only its `def` line run has no test.", ""]
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name not in CLASSES:
            continue
        rows, untested_broadcast = [], []
        for item in node.body:
            if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            executed, executable = coverage.get(f"{node.name}.{item.name}", [0, 0])
            area = "B" if BROADCAST.search(item.name) else ""
            tested = executed > 1 or executable <= 1
            if area and not tested:
                untested_broadcast.append(item.name)
            rows.append(f"| `{item.name}` | {item.lineno} | {executed} / {executable} | {area} | "
                        f"{'yes' if tested else '**no**'} |")
        covered = sum(1 for row in rows if row.endswith("yes |"))
        out += [f"## {node.name} ({len(rows)} methods, {covered} with a test)", "",
                "| Method | Line | Lines run | Area | Tested |", "|---|---|---|---|---|", *rows, ""]
        out += [f"Broadcast-area methods of {node.name} without a test: "
                + (", ".join(f"`{name}`" for name in untested_broadcast) or "none") + ".", ""]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
